        Noty.toast({
            type: 'success',
            message: 'محصول با موفقیت ویرایش شد',
            duration: 4000,
        });
    });
    Livewire.on('product.changeStatus', () => {
        Noty.toast({
            type: 'success',
            message: 'وضعیت محصول با موفقیت ویراش شد',
            duration: 4000,
        });
    });
    Livewire.on('delete', (event) => {
        Noty.delete({
            title: 'حذف محصول',
            text: 'آیا از حذف این محصول بندی مطمئنید؟ این عمل قابل بازگشت نیست و تمام اطلاعات محصول از جمله رنگ، سایز آن  نیز برای همیشه حذف خواهد شد.',
            confirmText: 'بله، حذف کن',
        }).then(ok => {
            if (ok) {
                Livewire.dispatch('product.delete', {product_id: event.product_id});
                Noty.toast({
                    type: 'error',
                    message: 'محصول حذف شد.',
                    duration: 8000
                });
            }
        });
    })
